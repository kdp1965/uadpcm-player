"""mksongs.py > songs/songs.js - the list of the .ua files in web/songs that
the web player offers as ready-made songs.  Run it in web/ after adding or
removing one.  The title is the file name with spaces put back
(CanYouFeelTheLoveTonight.ua -> "Can You Feel The Love Tonight")."""
import glob
import json
import os
import re
import struct

songs = []
for path in sorted(glob.glob(os.path.join(os.path.dirname(os.path.abspath(__file__)), "songs", "*.ua"))):
    with open(path, "rb") as f:
        magic, samples, rate = struct.unpack("<4sII", f.read(12))
    if magic != b"uADP":
        continue
    stem = os.path.splitext(os.path.basename(path))[0]
    title = re.sub(r"[_-]+", " ", re.sub(r"(?<=[a-z0-9])(?=[A-Z])", " ", stem)).strip()
    songs.append({"file": os.path.basename(path), "title": title, "samples": samples, "rate": rate,
                  "bytes": os.path.getsize(path)})
print("// Generated by web/mksongs.py - do not edit.")
print("self.UA_SONGS = " + json.dumps(songs, indent=2) + ";")
