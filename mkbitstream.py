"""mkbitstream.py FILE.bin NAME > bitstream.js - the FPGA bitstream as a
script the web player loads (it works from file:// too, where fetch does
not).  Run by `make web` in fpga/."""
import base64
import sys

blob = open(sys.argv[1], "rb").read()
b64 = base64.b64encode(blob).decode()
print("// Generated by web/mkbitstream.py (make -C fpga web) - do not edit.")
print("// %s for the Tiny Tapeout FPGA breakout (iCE40UP5K), %d bytes." % (sys.argv[2], len(blob)))
print("(function (root) {")
print('  const m = { name: "%s", size: %d, b64:' % (sys.argv[2], len(blob)))
for i in range(0, len(b64), 120):
    print('    "%s"%s' % (b64[i:i + 120], " +" if i + 120 < len(b64) else " };"))
print('  if (typeof module === "object" && module.exports) module.exports = m; else root.UA_BITSTREAM = m;')
print('})(typeof self !== "undefined" ? self : this);')
